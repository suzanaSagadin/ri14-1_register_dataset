"""Step 9: write stats.md from the built files."""
import collections

from .common import ROOT, DATA, REVIEW, read_jsonl


def run():
    entities = read_jsonl(DATA / "entities.jsonl")
    digests = read_jsonl(DATA / "digests.jsonl")
    mentions = read_jsonl(DATA / "mentions.jsonl")
    by_type = collections.Counter(e["type"] for e in entities)
    conf = collections.Counter((e["type"], e.get("type_confidence") or e["classification"]["confidence"]) for e in entities)
    persons = [e for e in entities if e["type"] == "person"]
    freq = collections.Counter(len(e["digests"]) for e in persons)

    def mt(m):
        return m.get("auto_match") or m["match"]

    match = collections.Counter(mt(m) for m in mentions if m["entity_type"] == "person")
    match_all = collections.Counter(mt(m) for m in mentions)
    src = collections.Counter(m["source"] for m in mentions)
    verdict = collections.Counter(m.get("verdict") for m in mentions if m.get("verdict"))
    kind = collections.Counter(m.get("kind") for m in mentions if m.get("text"))
    agree = collections.Counter((mt(m), m.get("verdict")) for m in mentions if m.get("verdict"))
    with_string = sum(1 for m in mentions if m.get("text"))
    n_cat = len(open(DATA / "splits" / "catalogue_digests.txt", encoding="utf-8").read().splitlines())
    n_test = len(open(DATA / "splits" / "test_digests.txt", encoding="utf-8").read().splitlines())
    n_review = sum(1 for _ in open(REVIEW / "uncertain_entities.tsv", encoding="utf-8")) - 1
    n_unres = sum(1 for _ in open(REVIEW / "unresolved_redirects.tsv", encoding="utf-8")) - 1
    top = sorted(persons, key=lambda e: -len(e["digests"]))[:15]

    L = ["# Dataset statistics", "", "Generated by `build.py`; do not edit by hand.", "",
         "## Digests", "", "| | n |", "|---|---|",
         f"| Digests in RI XIV,1 | {len(digests)} |",
         f"| Digests with at least one person | {sum(1 for d in digests if d['entities']['person'])} |",
         f"| Digests with at least one entity of any type | {sum(1 for d in digests if any(d['entities'].values()))} |",
         "", "## Entities", "", "| type | n | curated with high confidence | medium | low |", "|---|---|---|---|---|"]
    for t in ("person", "place", "other"):
        L.append(f"| {t} | {by_type[t]} | {conf[(t,'high')]} | {conf[(t,'medium')]} | {conf[(t,'low')]} |")
    sub = collections.Counter((e["type"], e.get("subtype")) for e in entities)
    tsrc = collections.Counter(e.get("type_source") for e in entities)
    tconf = collections.Counter(e.get("type_confidence") for e in entities if e.get("type_source") != "parser")
    L += ["", "| type | subtype | n |", "|---|---|---|"] + [f"| {t} | {st} | {n} |" for (t, st), n in sorted(sub.items(), key=lambda x: (x[0][0], -x[1]))]
    L += ["", "| type decided by | entities |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(tsrc.items(), key=str)]
    L += ["", "| type confidence (curated) | entities |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(tconf.items(), key=str)]
    L += ["", f"Entries flagged for review: {n_review} (`review/uncertain_entities.tsv`), "
              f"unresolved redirects: {n_unres} (`review/unresolved_redirects.tsv`).", "",
          "## Persons by number of digests", "", "| digests per person | persons |", "|---|---|",
          f"| 1 | {freq[1]} |", f"| 2 to 4 | {sum(v for k, v in freq.items() if 2 <= k <= 4)} |",
          f"| 5 to 9 | {sum(v for k, v in freq.items() if 5 <= k <= 9)} |",
          f"| 10 or more | {sum(v for k, v in freq.items() if k >= 10)} |",
          f"| person-digest links | {sum(len(e['digests']) for e in persons)} |",
          "", "## Mention strings", "",
          f"| | n |", "|---|---|", f"| entity-digest links | {len(mentions)} |",
          f"| links with a mention string | {with_string} |",
          f"| links curated | {sum(verdict.values())} |", "",
          "Automatic finder result per link (before curation):", "",
          "| finder match type | person links | all links |", "|---|---|---|"]
    L += [f"| {k} | {match[k]} | {match_all[k]} |" for k in ("exact", "variant", "stem", "given_name", "none")]
    L += ["", "Curation verdicts (`confirmed` = finder string kept, `corrected` = string changed, "
              "`filled` = finder found nothing, `absent` = entity not referred to in the text):", "",
          "| verdict | links |", "|---|---|"] + [f"| {k} | {verdict[k]} |" for k in ("confirmed", "corrected", "filled", "absent")]
    L += ["", "Finder precision by match type (share of links the curation confirmed unchanged):", "",
          "| finder match type | confirmed | corrected | absent | precision |", "|---|---|---|---|---|"]
    for k in ("exact", "variant", "stem", "given_name"):
        c, w, a = agree[(k, "confirmed")], agree[(k, "corrected")], agree[(k, "absent")]
        L.append(f"| {k} | {c} | {w} | {a} | {c / (c + w + a):.0%} |" if c + w + a else f"| {k} | 0 | 0 | 0 | - |")
    L += ["", "| kind of mention | links with a string |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(kind.items())]
    L += ["", "| source of the decision | links |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(src.items())]
    L += ["", "## Split", "", "| | n |", "|---|---|", f"| Catalogue digests | {n_cat} |", f"| Test digests | {n_test} |",
          "", "## Most frequent persons", "", "| id | label | digests |", "|---|---|---|"]
    L += [f"| {e['id']} | {e['label']} | {len(e['digests'])} |" for e in top]
    (ROOT / "stats.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("  wrote stats.md")
